import AppKit
import ApplicationServices
import CoreGraphics

@MainActor
final class TextInsertionService {
    /// How long to leave the dictation on the pasteboard before putting the
    /// user's clipboard back. Slow apps (Electron, a busy terminal) can take
    /// a while to service ⌘V; restoring too early pastes the old clipboard.
    static let restoreDelay: Duration = .milliseconds(800)

    /// Tells clipboard managers (Raycast, Paste, Maccy…) not to record the
    /// pasteboard contents — see nspasteboard.org.
    private static let transientMarkers: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// The user's clipboard, held while a restore is pending. A second
    /// dictation inside the restore window reuses it rather than saving the
    /// first dictation's text as "the user's clipboard".
    private var savedContents: [[NSPasteboard.PasteboardType: Data]]?
    private var restoreTask: Task<Void, Never>?

    /// Pastes `text` into the focused app and returns without waiting for
    /// the clipboard restore, so the next dictation isn't held up by it.
    func insertText(_ text: String) {
        let pasteboard = NSPasteboard.general
        restoreTask?.cancel()
        let previousContents = savedContents ?? savePasteboard(pasteboard)
        savedContents = previousContents

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        for marker in Self.transientMarkers {
            pasteboard.setData(Data(), forType: marker)
        }
        let ourChangeCount = pasteboard.changeCount

        simulatePaste()

        restoreTask = Task { [weak self] in
            try? await Task.sleep(for: Self.restoreDelay)
            guard !Task.isCancelled, let self else { return }
            self.savedContents = nil
            // The user copied something during the window — keep that.
            guard pasteboard.changeCount == ourChangeCount else { return }
            self.restorePasteboard(pasteboard, items: previousContents)
        }
    }

    /// The character just before the cursor in the focused text field, via
    /// Accessibility. Nil at the start of a field, when text is selected
    /// (it's about to be replaced), or when the app doesn't expose its text
    /// (many terminals and Electron apps).
    func characterBeforeCursor() -> Character? {
        // Short timeout: a hung frontmost app must not stall dictation.
        guard let focused = FocusedElement.current(timeout: 0.25) else { return nil }

        var rangeRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(focused, kAXSelectedTextRangeAttribute as CFString, &rangeRef) == .success,
              let rangeRef, CFGetTypeID(rangeRef) == AXValueGetTypeID() else { return nil }
        var selection = CFRange()
        guard AXValueGetValue(rangeRef as! AXValue, .cfRange, &selection),
              selection.length == 0, selection.location > 0 else { return nil }

        // Ask for several UTF-16 units: enough that an emoji isn't split,
        // and enough to see past zero-width characters to the real one.
        let start = max(0, selection.location - 8)
        var precedingRange = CFRange(location: start, length: selection.location - start)
        guard let precedingValue = AXValueCreate(.cfRange, &precedingRange) else { return nil }
        var stringRef: CFTypeRef?
        guard AXUIElementCopyParameterizedAttributeValue(
            focused,
            kAXStringForRangeParameterizedAttribute as CFString,
            precedingValue,
            &stringRef
        ) == .success, let preceding = stringRef as? String else { return nil }
        return SmartSpacing.lastVisibleCharacter(in: preceding)
    }

    private func savePasteboard(_ pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        var saved: [[NSPasteboard.PasteboardType: Data]] = []
        guard let items = pasteboard.pasteboardItems else { return saved }
        for item in items {
            var itemData: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    itemData[type] = data
                }
            }
            saved.append(itemData)
        }
        return saved
    }

    private func restorePasteboard(_ pasteboard: NSPasteboard, items: [[NSPasteboard.PasteboardType: Data]]) {
        guard !items.isEmpty else { return }
        pasteboard.clearContents()
        var pasteboardItems: [NSPasteboardItem] = []
        for itemData in items {
            let item = NSPasteboardItem()
            for (type, data) in itemData {
                item.setData(data, forType: type)
            }
            pasteboardItems.append(item)
        }
        pasteboard.writeObjects(pasteboardItems)
    }

    /// Types `text` into the focused app as keyboard events, a few
    /// characters per event. Used for live insertion, where pasting every
    /// word would thrash the clipboard.
    func typeText(_ text: String) {
        let source = CGEventSource(stateID: .hidSystemState)
        var chunk: [UniChar] = []
        func flush() {
            guard !chunk.isEmpty else { return }
            let down = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true)
            let up = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false)
            down?.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
            up?.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
            down?.post(tap: .cgAnnotatedSessionEventTap)
            up?.post(tap: .cgAnnotatedSessionEventTap)
            chunk.removeAll()
        }
        for unit in text.utf16 {
            chunk.append(unit)
            // Keep each event under the size apps reliably accept.
            if chunk.count >= 20, !UTF16.isLeadSurrogate(unit) { flush() }
        }
        flush()
    }

    /// Presses Delete `count` times in the focused app.
    func deleteBackward(count: Int) {
        guard count > 0 else { return }
        let source = CGEventSource(stateID: .hidSystemState)
        for _ in 0..<count {
            let down = CGEvent(keyboardEventSource: source, virtualKey: 0x33, keyDown: true)
            let up = CGEvent(keyboardEventSource: source, virtualKey: 0x33, keyDown: false)
            down?.post(tap: .cgAnnotatedSessionEventTap)
            up?.post(tap: .cgAnnotatedSessionEventTap)
        }
    }

    private func simulatePaste() {
        let source = CGEventSource(stateID: .hidSystemState)

        let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true) // 0x09 = V
        keyDown?.flags = .maskCommand

        let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false)
        keyUp?.flags = .maskCommand

        keyDown?.post(tap: .cgAnnotatedSessionEventTap)
        keyUp?.post(tap: .cgAnnotatedSessionEventTap)
    }
}
